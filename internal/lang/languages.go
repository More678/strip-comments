package lang

// This file is the language table. Every entry is plain data; lang.go documents
// each field and internal/scan interprets them.

// q is a literal opened and closed by the same delimiter.
func q(delim string, esc byte, multi bool) StringRule {
	return StringRule{Start: delim, End: delim, Escape: esc, Multiline: multi}
}

// span is a literal with distinct start and end delimiters.
func span(start, end string, esc byte, multi bool) StringRule {
	return StringRule{Start: start, End: end, Escape: esc, Multiline: multi}
}

// dbl is a literal whose delimiter is escaped by writing it twice ('it”s').
func dbl(delim string, multi bool) StringRule {
	return StringRule{Start: delim, End: delim, Doubled: true, Multiline: multi}
}

// verbatim is a C# @"..." literal: no escapes, `""` is a literal quote.
func verbatim(start string) StringRule {
	return StringRule{Start: start, End: `"`, Doubled: true, Multiline: true}
}

func ln(tok string) LineComment { return LineComment{Token: tok} }

func blk(start, end string) BlockComment { return BlockComment{Start: start, End: end} }

func nested(start, end string) BlockComment {
	return BlockComment{Start: start, End: end, Nested: true}
}

// slashLine returns `//` plus the given doc tokens ("///", "//!"). A `////`
// separator is never documentation, so it is added whenever "///" is.
func slashLine(cont bool, docs ...string) []LineComment {
	l := []LineComment{{Token: "//", BackslashCont: cont}}
	for _, d := range docs {
		l = append(l, LineComment{Token: d, Doc: true, BackslashCont: cont})
		if d == "///" {
			l = append(l, LineComment{Token: "////", BackslashCont: cont})
		}
	}
	return l
}

// slashBlock returns `/* */` plus the given doc openers ("/**", "/*!").
// With "/**" present the empty comment `/**/` would open a doc comment whose
// `*/` overlaps its start, so it gets its own rule with an empty End.
func slashBlock(nest bool, docs ...string) []BlockComment {
	b := []BlockComment{{Start: "/*", End: "*/", Nested: nest}}
	for _, d := range docs {
		b = append(b, BlockComment{Start: d, End: "*/", Nested: nest, Doc: true})
		if d == "/**" {
			b = append(b, BlockComment{Start: "/**/", End: "", Nested: nest})
		}
	}
	return b
}

// cQuotes is the C-family `"..."` rule: backslash escapes, no raw newline.
var cQuotes = []StringRule{q(`"`, '\\', false)}

// sigils builds `prefix+open ... close` rules for every delimiter pair, used
// for Ruby %q(...), Elixir ~r/.../ and similar quote-like operators.
func sigils(prefixes []string, esc byte, pairs ...string) []StringRule {
	var out []StringRule
	for _, p := range prefixes {
		for i := 0; i+1 < len(pairs); i += 2 {
			out = append(out, span(p+pairs[i], pairs[i+1], esc, true))
		}
	}
	return out
}

// jsQuotes covers JS/TS: template literals span lines, plain quotes do not.
var jsQuotes = []StringRule{q(`"`, '\\', false), q(`'`, '\\', false), q("`", '\\', true)}

// Delimiter pairs accepted by quote-like operators.
var (
	bracketPairs = []string{"(", ")", "[", "]", "{", "}", "<", ">"}
	quotePairs   = []string{"|", "|", "/", "/", `"`, `"`, "'", "'"}

	// elixirSigils: ~r regex, ~s/~c strings, ~w word lists, ~D/~T/~N/~U dates.
	elixirSigils = []string{"~r", "~R", "~s", "~S", "~w", "~W", "~c", "~C",
		"~D", "~T", "~N", "~U"}
)

// texVerbatim protects environments and macros whose `%` is literal text.
func texVerbatim() []StringRule {
	var out []StringRule
	for _, env := range []string{"verbatim", "verbatim*", "lstlisting", "minted",
		"Verbatim", "comment", "filecontents", "filecontents*"} {
		out = append(out, span(`\begin{`+env+`}`, `\end{`+env+`}`, 0, true))
	}
	for _, m := range []string{`\url{`, `\href{`, `\path{`} {
		out = append(out, span(m, "}", 0, false))
	}
	for _, d := range []string{"|", "+", "!", "=", "/"} {
		out = append(out, span(`\verb`+d, d, 0, false))
	}
	return out
}

